_NAMED = re.compile(r"&([A-Za-z][A-Za-z0-9]*);")


def _named(m: re.Match) -> str:
    name = m.group(1)
    return chr(ENTITIES[name]) if name in ENTITIES else m.group(0)


def unescape_html(s: str) -> str:
    return _NAMED.sub(_named, s)
